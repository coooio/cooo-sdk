import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { randomBytes } from 'node:crypto';

const metadataPath = new URL('../.cooo-devnet/devnet.json', import.meta.url);
const metadata = JSON.parse(await readFile(metadataPath, 'utf8'));

async function rpc(method, params) {
  const response = await fetch(metadata.rpcUrl, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({ jsonrpc: '2.0', id: 1, method, params }),
    signal: AbortSignal.timeout(3000),
  });
  if (!response.ok) throw new Error(`RPC ${method} returned HTTP ${response.status}`);
  const payload = await response.json();
  if (payload.error) throw new Error(payload.error.message ?? 'JSON-RPC error');
  return payload.result;
}

const accounts = await rpc('eth_accounts', []);
if (!Array.isArray(accounts) || accounts.length < 4) {
  throw new Error('The local devnet must expose at least four unlocked accounts');
}
const unique = new Set(accounts.slice(0, 4).map(account => account.toLowerCase()));
if (unique.size !== 4) throw new Error('Unlocked devnet accounts are not distinct');

const root = fileURLToPath(new URL('..', import.meta.url));
const envPath = path.join(root, '.cooo-devnet', 'reviewed-task.env');
const taskId = `quickstart-${randomBytes(6).toString('hex')}`;
const deadline = new Date(Date.now() + 86_400_000).toISOString();
const environment = [
  '# Generated by devnet/provision-env.mjs; local synthetic configuration only.',
  `COOO_RPC_URL=${metadata.rpcUrl}`,
  `COOO_INFO_URL=${metadata.infoUrl}`,
  `COOO_STATE_URL=${metadata.stateUrl}`,
  `COOO_LYQUID_ID=${metadata.lyquidId}`,
  `COOO_CONTRACT=${metadata.contract}`,
  `COOO_OPERATOR=${accounts[0]}`,
  `COOO_REQUESTER=${accounts[1]}`,
  `COOO_PROVIDER=${accounts[2]}`,
  `COOO_REVIEWER=${accounts[3]}`,
  `COOO_TASK_ID=${taskId}`,
  `COOO_DEADLINE=${deadline}`,
  '',
].join('\n');
await writeFile(envPath, environment, 'utf8');
console.log(JSON.stringify({ envFile: envPath, taskId, deadline }, null, 2));
